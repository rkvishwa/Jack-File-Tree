import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const packageJsonPath = require.resolve("material-icon-theme/package.json");
const packageRoot = dirname(packageJsonPath);
const manifestPath = resolve(packageRoot, "dist/material-icons.json");
const iconsDir = resolve(packageRoot, "icons");
const outputPath = resolve(process.cwd(), "src/icons/materialIconData.generated.ts");

const materialPackage = JSON.parse(await readFile(packageJsonPath, "utf8"));
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

function iconPathToName(iconPath) {
  return iconPath.replace(/^\.\/\.\.\/icons\//, "");
}

function toDataUrl(svgText) {
  return `data:image/svg+xml,${encodeURIComponent(svgText)
    .replace(/'/g, "%27")
    .replace(/\(/g, "%28")
    .replace(/\)/g, "%29")}`;
}

const iconFileNames = new Map();

for (const [iconName, definition] of Object.entries(manifest.iconDefinitions)) {
  if (definition?.iconPath) {
    iconFileNames.set(iconName, iconPathToName(definition.iconPath));
  }
}

const iconDataUrls = {};

for (const [iconName, fileName] of iconFileNames) {
  const svgText = await readFile(resolve(iconsDir, fileName), "utf8");
  iconDataUrls[iconName] = toDataUrl(svgText);
}

const source = `/* eslint-disable */\n` +
  `// Generated by scripts/generate-material-icons.mjs from material-icon-theme ${materialPackage.version}.\n` +
  `// Do not edit by hand.\n\n` +
  `export const materialIconDataUrls: Record<string, string> = ${JSON.stringify(iconDataUrls)};\n\n` +
  `export const materialIconFileExtensions: Record<string, string> = ${JSON.stringify(manifest.fileExtensions ?? {})};\n\n` +
  `export const materialIconFileNames: Record<string, string> = ${JSON.stringify(manifest.fileNames ?? {})};\n\n` +
  `export const materialIconFolderNames: Record<string, string> = ${JSON.stringify(manifest.folderNames ?? {})};\n\n` +
  `export const materialIconFolderNamesExpanded: Record<string, string> = ${JSON.stringify(manifest.folderNamesExpanded ?? {})};\n\n` +
  `export const materialIconDefaults = ${JSON.stringify({
    file: manifest.file,
    folder: manifest.folder,
    folderExpanded: manifest.folderExpanded,
    rootFolder: manifest.rootFolder,
    rootFolderExpanded: manifest.rootFolderExpanded,
  })} as const;\n`;

await writeFile(outputPath, source);
